-- 내전하자 초기 스키마
-- (H2 의 PostgreSQL 호환 모드에서도 돌아가도록 표준 SQL 위주로 작성)

-- 방(그룹): 디스코드 서버/친구 모임 단위. 입장 코드 + 비밀번호로 들어온다.
CREATE TABLE inhouse_group (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(12)  NOT NULL UNIQUE,
    name          VARCHAR(40)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 단골 멤버
CREATE TABLE member (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id        BIGINT       NOT NULL REFERENCES inhouse_group (id) ON DELETE CASCADE,
    name            VARCHAR(40)  NOT NULL,          -- 화면 표시 이름 (Riot ID 또는 별명)
    name_key        VARCHAR(40)  NOT NULL,          -- 중복 검사용 (소문자, 공백 제거)
    riot_id         VARCHAR(40),                    -- 이름#태그 (직접 추가한 멤버는 NULL)
    puuid           VARCHAR(100),
    profile_icon_id INTEGER,
    tier            VARCHAR(20)  NOT NULL,
    lp              INTEGER,
    lines_json      TEXT         NOT NULL DEFAULT '[]',
    mmr_override    INTEGER,                        -- 직접 정한 MMR (NULL 이면 티어로 계산)
    inhouse_delta   INTEGER      NOT NULL DEFAULT 0, -- 내전 승패로 누적된 보정치
    wins            INTEGER      NOT NULL DEFAULT 0,
    losses          INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_member_name UNIQUE (group_id, name_key)
);
CREATE INDEX ix_member_group ON member (group_id);

-- 내전 한 판 (팀 구성 결과를 저장한 것)
CREATE TABLE inhouse_match (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   VARCHAR(16)  NOT NULL UNIQUE,       -- 공유 링크용
    group_id    BIGINT       NOT NULL REFERENCES inhouse_group (id) ON DELETE CASCADE,
    mode        VARCHAR(10)  NOT NULL,              -- RIFT / ABYSS
    blue_total  INTEGER      NOT NULL,
    red_total   INTEGER      NOT NULL,
    mmr_diff    INTEGER      NOT NULL,
    balance     VARCHAR(12)  NOT NULL,
    winner      VARCHAR(4),                         -- BLUE / RED / NULL(미정)
    memo        VARCHAR(100),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_match_group_created ON inhouse_match (group_id, created_at);

CREATE TABLE inhouse_match_player (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id      BIGINT      NOT NULL REFERENCES inhouse_match (id) ON DELETE CASCADE,
    member_id     BIGINT      REFERENCES member (id) ON DELETE SET NULL,
    slot          INTEGER     NOT NULL,             -- 팀 안 순서 (0~4)
    team          VARCHAR(4)  NOT NULL,             -- BLUE / RED
    name          VARCHAR(40) NOT NULL,
    tier          VARCHAR(20) NOT NULL,
    line          VARCHAR(10),
    line_role     VARCHAR(10),
    base_mmr      INTEGER     NOT NULL,
    mmr           INTEGER     NOT NULL,
    rating_delta  INTEGER     NOT NULL DEFAULT 0    -- 승패 기록 시 이 선수에게 준 내전 보정치 (되돌리기용)
);
CREATE INDEX ix_match_player_match ON inhouse_match_player (match_id);
CREATE INDEX ix_match_player_member ON inhouse_match_player (member_id);

-- 소환사 분석 캐시 (방과 무관, 모두 공유). 같은 소환사를 다시 불러오면 Riot 호출 없이 바로 응답.
CREATE TABLE summoner_insight (
    puuid        VARCHAR(100) PRIMARY KEY,
    riot_id      VARCHAR(40)  NOT NULL,
    lines_json   TEXT         NOT NULL,
    stats_json   TEXT         NOT NULL,
    sample_size  INTEGER      NOT NULL,
    computed_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 서버 설정값 (예: 방 입장 토큰 서명 키를 처음 실행할 때 만들어 저장 → 재시작해도 로그인 유지)
CREATE TABLE app_setting (
    k VARCHAR(40)  PRIMARY KEY,
    v VARCHAR(200) NOT NULL
);
